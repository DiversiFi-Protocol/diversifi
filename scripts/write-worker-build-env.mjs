// Next.js inlines NEXT_PUBLIC_* settings into everything it builds, server code included; wrangler, which bundles the
// Worker, does not. This loads them exactly as `next build` does (process environment, then the .env files) and writes
// them into a module the Worker applies before any lib/ code reads them (worker/build-env.ts). Runs in `npm run build`.
import { writeFileSync } from 'node:fs';
import nextEnv from '@next/env';

nextEnv.loadEnvConfig(process.cwd(), false);
const NAMES = ['NEXT_PUBLIC_SITE_URL', 'NEXT_PUBLIC_RPC_URL'];
const values = Object.fromEntries(NAMES.map(name => [name, process.env[name] || null]));
writeFileSync(
  new URL('../worker/build-env.generated.ts', import.meta.url),
  `// Generated by scripts/write-worker-build-env.mjs during \`npm run build\`. Do not edit.\nexport const BUILD_ENV: Record<string, string | null> = ${JSON.stringify(values, null, 2)};\n`,
);
